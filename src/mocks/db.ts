/** Authorization 헤더의 mock 토큰을 파싱해 사용자 식별. */
export function userFromAuthHeader(authHeader: string | null): User | null {
  if (!authHeader?.startsWith('Bearer ')) return null
  const token = authHeader.slice(7)
  // dev-mock-token-{role.lower}
  if (token === 'dev-mock-token-super_admin')
    return db.users.find((u) => u.role === 'SUPER_ADMIN') ?? null
  if (token === 'dev-mock-token-president')
    return db.users.find((u) => u.id === 101) ?? null
  if (token === 'dev-mock-token-member')
    return db.users.find((u) => u.id === 102) ?? null
  // fallback: 토큰이 어떤 형식이든 PRESIDENT 사용자 반환
  return db.users.find((u) => u.id === 101) ?? null
}
